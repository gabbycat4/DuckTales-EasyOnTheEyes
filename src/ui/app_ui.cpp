extern "C" bool app_menu_run(SDL_Window *win)
{
    SDL_Renderer *ren = SDL_GetRenderer(win);
    if (!ren) {
        return false;
    }
    int lw = 0, lh = 0;
    SDL_RenderGetLogicalSize(ren, &lw, &lh);
    SDL_Texture *target = SDL_GetRenderTarget(ren);
    SDL_SetRenderTarget(ren, nullptr);
    Imgui imgui;
    if (!imgui.begin(win, ren)) {
        SDL_SetRenderTarget(ren, target);
        return false;
    }
    ui::Logo logo(app_about_logo_png, app_about_logo_png_size, { ren, logo_texture, logo_release });
    const ui::About about_info = about(&logo);
    ui::Menu *menu_ref = nullptr;
    ui::Menu menu(
        {
            { "Settings",
              { { "General", page_general },
                { "Graphics",
                  [win] {
                      page_graphics(win);
                  } },
                { "Audio",
                  [win] {
                      page_audio(win);
                  } },
                { "Controls",
                  [&menu_ref] {
                      ui::section("Player 1");
                      ui::binding_table(*menu_ref, bindings());
                  } },
                { "Gameplay", page_gameplay },
                { "Mods", page_mods } },
              nullptr },
            { "Enhancements",
              { { "Gameplay", page_enh_gameplay }, { "Restore defaults", page_enh_defaults } },
              nullptr },
            { "About",
              {},
              [&about_info] {
                  ui::about_page(about_info);
              } },
        },
        {
            { "##reset", ui::Icon::reset, false, "Reset the game?", "Reset" },
            { "##quit", ui::Icon::quit, true, "Quit DuckTales?", "Quit" },
            { "##resume", ui::Icon::resume },
        });
    menu_ref = &menu;
    int pic_w = 0, pic_h = 0;
    bool pic_exact = false;
    SDL_Texture *pic = nullptr;
    auto update_picture = [&](int out_w, int out_h) {
        int w = 0, h = 0;
        const uint32_t *picture = app_ui_picture(out_w, out_h, &w, &h, &pic_exact);
        if (!picture) {
            return;
        }
        if (!pic || w != pic_w || h != pic_h) {
            if (pic) {
                SDL_DestroyTexture(pic);
            }
            pic = SDL_CreateTexture(ren, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_STATIC, w, h);
            if (!pic) {
                return;
            }
            SDL_SetTextureScaleMode(pic, SDL_ScaleModeNearest);
            pic_w = w;
            pic_h = h;
        }
        SDL_UpdateTexture(pic, nullptr, picture, w * 4);
    };
    std::printf("[ducktales] menu open\n");
    std::fflush(stdout);
    bool resume = false, quit = false, confirming = false;
    long game_frames = 0;
    std::vector<SDL_Event> for_host;
    Uint64 last = SDL_GetTicks64();

    struct Step {
        int tab, category, capture, popup, w, h;
        bool focus;
        const char *name;
    };

    static const Step SCRIPT[] = {
        { TAB_SETTINGS, 0, -1, -1, 0, 0, false, "menu_01_settings_general" },
        { TAB_SETTINGS, 1, -1, -1, 0, 0, true, "menu_02_settings_graphics" },
        { TAB_SETTINGS, 2, -1, -1, 0, 0, false, "menu_03_settings_audio" },
        { TAB_SETTINGS, 3, -1, -1, 0, 0, false, "menu_04_settings_controls" },
        { TAB_SETTINGS, 3, 0, -1, 0, 0, false, "menu_05_settings_controls_capture" },
        { TAB_SETTINGS, 4, -1, -1, 0, 0, false, "menu_06_settings_gameplay" },
        { TAB_ENHANCEMENTS, 0, -1, -1, 0, 0, false, "menu_07_enhancements_gameplay" },
        { TAB_ENHANCEMENTS, 1, -1, -1, 0, 0, false, "menu_08_enhancements_restore_defaults" },
        { TAB_ABOUT, 0, -1, -1, 0, 0, false, "menu_09_about" },
        { TAB_SETTINGS, 1, -1, -1, 1280, 720, false, "menu_10_settings_graphics_720p" },
        { TAB_SETTINGS, 1, -1, -1, 3840, 2160, false, "menu_11_settings_graphics_2160p" },
        { TAB_ABOUT, 0, -1, -1, 3840, 2160, false, "menu_12_about_2160p" },
        { TAB_SETTINGS, 0, -1, BUTTON_RESET, 0, 0, false, "menu_13_reset" },
        { TAB_SETTINGS, 0, -1, BUTTON_QUIT, 0, 0, false, "menu_14_quit" },
    };
    const bool selftest = selftest_dir() != nullptr;
    size_t step = 0;
    int step_frames = 0;
    SDL_Texture *offscreen = nullptr;
    int off_w = 0, off_h = 0;
    auto apply_step = [&](const Step &s) {
        menu.select(s.tab, s.category);
        if (s.capture >= 0) {
            menu.begin_capture(&bindings(), s.capture, 0);
        } else {
            menu.end_capture();
        }
        menu.ask(s.popup);
        if (s.focus) {
            menu.focus_page();
        }
    };
    if (selftest) {
        apply_step(SCRIPT[0]);
    }
    while (!resume && !quit) {
        SDL_Event ev;
        while (SDL_PollEvent(&ev)) {
            if (ev.type == SDL_QUIT) {
                quit = true;
                continue;
            }
            if ((ev.type == SDL_WINDOWEVENT && ev.window.event == SDL_WINDOWEVENT_SIZE_CHANGED) ||
                ev.type == SDL_CONTROLLERDEVICEADDED || ev.type == SDL_CONTROLLERDEVICEREMOVED) {
                for_host.push_back(ev);
            }
            const ui::EventResult r = menu.event(translate(ev));
            if (r == ui::EventResult::close) {
                resume = true;
            }
            if (r != ui::EventResult::pass) {
                continue;
            }
            ImGui_ImplSDL2_ProcessEvent(&ev);
        }
        if (resume || quit) {
            break;
        }
        AppMenuPrefs prefs;
        app_menu_prefs_get(&prefs);
        imgui.ctx->set_gamepad_navigation(prefs.pad_nav != 0);
        if (s_menu_tick && !prefs.pause && !confirming) {
            game_frames += s_menu_tick();
        }
        ImGuiIO &io = ImGui::GetIO();
        SDL_RenderSetLogicalSize(ren, 0, 0);
        SDL_RenderSetViewport(ren, nullptr);
        int ow = 0, oh = 0;
        SDL_GetRendererOutputSize(ren, &ow, &oh);
        bool off = false;
        if (selftest && SCRIPT[step].w > 0) {
            if (!offscreen || off_w != SCRIPT[step].w || off_h != SCRIPT[step].h) {
                if (offscreen) {
                    SDL_DestroyTexture(offscreen);
                }
                off_w = SCRIPT[step].w;
                off_h = SCRIPT[step].h;
                offscreen = SDL_CreateTexture(ren, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_TARGET, off_w, off_h);
            }
            off = offscreen && SDL_SetRenderTarget(ren, offscreen) == 0;
            if (off) {
                ow = off_w;
                oh = off_h;
            }
        }
        imgui.fit(ui_base(win, oh));
        SDL_SetRenderDrawColor(ren, 0, 0, 0, 255);
        SDL_RenderClear(ren);
        update_picture(ow, oh);
        draw_picture(ren, pic, pic_w, pic_h, pic_exact, ow, oh);

        ImGui_ImplSDLRenderer2_NewFrame();
        ImGui_ImplSDL2_NewFrame();
        if (off) {
            io.DisplaySize = ImVec2((float)ow, (float)oh);
            io.DisplayFramebufferScale = ImVec2(1.0f, 1.0f);
        }
        ImGui::NewFrame();
        switch (menu.draw(prefs.opacity)) {
            case BUTTON_RESET:
                dt_soft_reset();
                resume = true;
                break;
            case BUTTON_QUIT:
                quit = true;
                break;
            case BUTTON_RESUME:
                resume = true;
                break;
            default:
                break;
        }
        confirming = confirmation_open();
        ImGui::Render();
        ImGui_ImplSDLRenderer2_RenderDrawData(ImGui::GetDrawData(), ren);
        if (selftest && ++step_frames == 6) {
            selftest_shot(ren, ow, oh, SCRIPT[step].name);
            step_frames = 0;
            if (++step == sizeof SCRIPT / sizeof SCRIPT[0]) {
                resume = true;
            } else {
                apply_step(SCRIPT[step]);
            }
        }
        if (off) {
            SDL_SetRenderTarget(ren, nullptr);
        }
        SDL_RenderPresent(ren);
        Uint64 now = SDL_GetTicks64();
        if (now - last < 16) {
            SDL_Delay((Uint32)(16 - (now - last)));
        }
        last = SDL_GetTicks64();
    }
    if (offscreen) {
        SDL_DestroyTexture(offscreen);
    }
    if (pic) {
        SDL_DestroyTexture(pic);
    }
    logo.release();
    imgui.end();
    SDL_SetRenderTarget(ren, target);
    SDL_RenderSetLogicalSize(ren, lw, lh);
    SDL_SetRenderDrawBlendMode(ren, SDL_BLENDMODE_NONE);
    for (SDL_Event &ev : for_host) {
        SDL_PushEvent(&ev);
    }
    if (quit) {
        SDL_Event q;
        std::memset(&q, 0, sizeof q);
        q.type = SDL_QUIT;
        SDL_PushEvent(&q);
    }
    std::printf("[ducktales] menu closed%s, %ld game frames ran\n", quit ? " (quit)" : "", game_frames);
    std::fflush(stdout);
    return true;
}

