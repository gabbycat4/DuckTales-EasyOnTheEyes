extern "C" int app_ui_first_run(const char *expected, char *rom_out, size_t cap)
{
    if (SDL_Init(SDL_INIT_VIDEO | SDL_INIT_GAMECONTROLLER) != 0) {
        return 2;
    }
    const bool selftest = selftest_dir() != nullptr;
    SDL_Window *win = SDL_CreateWindow("DuckTales", SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED, 960, 640,
                                       SDL_WINDOW_RESIZABLE | SDL_WINDOW_ALLOW_HIGHDPI |
                                           (selftest ? SDL_WINDOW_HIDDEN : 0));
    int selftest_frames = 0;
    SDL_Renderer *ren = win ? SDL_CreateRenderer(win, -1, SDL_RENDERER_ACCELERATED | SDL_RENDERER_PRESENTVSYNC)
                            : nullptr;
    if (win && !ren) {
        ren = SDL_CreateRenderer(win, -1, 0);
    }
    Imgui imgui;
    if (!ren || !imgui.begin(win, ren)) {
        if (ren) {
            SDL_DestroyRenderer(ren);
        }
        if (win) {
            SDL_DestroyWindow(win);
        }
        SDL_Quit();
        return 2;
    }
    char data_dir[1024] = "";
    app_data_dir(data_dir, sizeof data_dir);
    const std::string where = std::string("Your copy is stored in ") +
                              (data_dir[0] ? data_dir : "your user data folder") + ".";
    std::string error, detail;
    int result = -1;
    Uint64 done_at = 0;
    std::string chosen;
    ui::FirstRunScreen screen;
    while (result < 0) {
        SDL_Event ev;
        while (SDL_PollEvent(&ev)) {
            if (ev.type == SDL_QUIT) {
                result = 1;
            }
            if (ev.type == SDL_DROPFILE) {
                chosen = ev.drop.file;
                SDL_free(ev.drop.file);
                continue;
            }
            ImGui_ImplSDL2_ProcessEvent(&ev);
        }
        if (!chosen.empty() && !done_at) {
            char actual[65] = "";
            AppRomStatus s = app_rom_import(chosen.c_str(), expected, rom_out, cap, actual);
            if (s == APP_ROM_OK) {
                error.clear();
                done_at = SDL_GetTicks64();
            } else {
                error = app_rom_status_text(s);
                detail = s == APP_ROM_MISMATCH
                             ? std::string("SHA-256 of this file: ") + actual + "\nExpected: " + expected
                             : std::string();
            }
            std::fprintf(stderr, "[ducktales] %s: %s\n", chosen.c_str(), app_rom_status_text(s));
            chosen.clear();
        }
        if (done_at && SDL_GetTicks64() - done_at > 900) {
            result = 0;
        }

        int ow = 0, oh = 0;
        SDL_GetRendererOutputSize(ren, &ow, &oh);
        imgui.fit(ui_base(win, oh));
        ImGui_ImplSDLRenderer2_NewFrame();
        ImGui_ImplSDL2_NewFrame();
        ImGui::NewFrame();
        ui::FirstRunContent content;
        content.app_title = "DuckTales Recompiled";
        content.title = "Choose your ROM";
        content.text = "This port runs on your own copy of the game. Choose your DuckTales (USA) cartridge image "
                       "(.nes), or drop it onto this window. It is checked against the original, then kept in "
                       "your user folder, so the game starts directly next time.";
        content.primary = "Choose ROM file\xE2\x80\xA6";
        content.secondary = "Quit";
        content.busy = done_at != 0;
        content.status = content.busy ? ui::Status::ok : error.empty() ? ui::Status::none : ui::Status::error;
        content.status_text = content.busy ? "Verified. Starting the game." : error.c_str();
        content.detail = detail.c_str();
        content.footer = where.c_str();
        const ui::FirstRunAction action = screen.draw(content);
        if (action == ui::FirstRunAction::primary) {
            chosen = pick_file(win);
        }
        if (action == ui::FirstRunAction::secondary) {
            result = 1;
        }
        ImGui::Render();
        SDL_SetRenderDrawColor(ren, 0, 0, 0, 255);
        SDL_RenderClear(ren);
        ImGui_ImplSDLRenderer2_RenderDrawData(ImGui::GetDrawData(), ren);
        if (selftest) {
            ++selftest_frames;
            if (selftest_frames == 6) {
                selftest_shot(ren, ow, oh, "first_run_1_welcome");
                const char *pick = std::getenv("DUCKTALES_UI_SELFTEST_PICK");
                if (pick && *pick) {
                    chosen = pick;
                } else {
                    result = 1;
                }
            }
            if (selftest_frames == 12) {
                selftest_shot(ren, ow, oh, "first_run_2_result");
                if (!done_at) {
                    result = 1;
                }
            }
        }
        SDL_RenderPresent(ren);
        SDL_Delay(1);
    }
    imgui.end();
    SDL_DestroyRenderer(ren);
    SDL_DestroyWindow(win);
    SDL_Quit();
    return result;
}
