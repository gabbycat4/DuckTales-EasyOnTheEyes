const char *bind_assign(int row, int column, const ui::InputEvent *e)
{
    const bool pad = column == 1;
    if (!e) {
        return app_bind_set(row, pad, 0);
    }
    if (e->type == ui::InputEvent::key_down) {
        return app_bind_set(row, false, e->code);
    }
    if (e->type == ui::InputEvent::button_down) {
        return app_bind_set(row, true, 1 + e->code);
    }
    return app_bind_set(row, true, 100 + e->code * 2 + (e->value > 0 ? 1 : 0));
}

const ui::BindingTable &bindings()
{
    static const ui::BindingTable table = [] {
        ui::BindingTable t;
        t.columns = { { "Keyboard", ui::Device::keyboard, "Press a key" },
                      { "Controller", ui::Device::gamepad, "Press a button" } };
        t.rows = APP_BIND_COUNT;
        t.label = app_bind_label;
        t.text = [](int row, int column, char *out, size_t cap) {
            app_bind_text(row, column == 1, out, cap);
            return std::strcmp(out, "Unbound") != 0;
        };
        t.assign = bind_assign;
        t.restore_label = "Restore default controls";
        t.restore = app_bind_defaults;
        return t;
    }();
    return table;
}

