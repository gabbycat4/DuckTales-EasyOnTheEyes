float ui_base(SDL_Window *win, int out_h)
{
    float ddpi = 0.0f;
    const int display = SDL_GetWindowDisplayIndex(win);
    if (display < 0 || SDL_GetDisplayDPI(display, &ddpi, nullptr, nullptr) != 0) {
        ddpi = 0.0f;
    }
    return ui::base_size(out_h, ddpi);
}

/* formae-ui's Linux default is Debian's DejaVu path; other distributions
 * (Arch/CachyOS, Fedora) keep their fonts elsewhere. */
static ui::FontFiles menu_fonts()
{
    ui::FontFiles f = ui::system_font_files();
#if !defined(_WIN32) && !defined(__APPLE__)
    static const char *const PAIRS[][2] = {
        { "/usr/share/fonts/noto/NotoSans-Regular.ttf", "/usr/share/fonts/noto/NotoSans-SemiBold.ttf" },
        { "/usr/share/fonts/TTF/DejaVuSans.ttf", "/usr/share/fonts/TTF/DejaVuSans-Bold.ttf" },
        { "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" },
        { "/usr/share/fonts/dejavu-sans-fonts/DejaVuSans.ttf", "/usr/share/fonts/dejavu-sans-fonts/DejaVuSans-Bold.ttf" },
        { "/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf", "/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf" },
    };
    for (const auto &pair : PAIRS) {
        FILE *a = std::fopen(pair[0], "rb"), *b = std::fopen(pair[1], "rb");
        bool ok = a && b;
        if (a) {
            std::fclose(a);
        }
        if (b) {
            std::fclose(b);
        }
        if (ok) {
            f.regular = pair[0];
            f.semibold = pair[1];
            break;
        }
    }
#endif
    return f;
}

struct Imgui {
    std::unique_ptr<ui::Context> ctx;

    bool begin(SDL_Window *w, SDL_Renderer *r)
    {
        ctx = std::make_unique<ui::Context>(ui::Theme(), menu_fonts());
        if (!ImGui_ImplSDL2_InitForSDLRenderer(w, r)) {
            ctx.reset();
            return false;
        }
        if (!ImGui_ImplSDLRenderer2_Init(r)) {
            ImGui_ImplSDL2_Shutdown();
            ctx.reset();
            return false;
        }
        int ow = 0, oh = 0;
        SDL_GetRendererOutputSize(r, &ow, &oh);
        fit(ui_base(w, oh));
        return true;
    }

    void fit(float base)
    {
        if (ctx->fit(base)) {
            ImGui_ImplSDLRenderer2_DestroyFontsTexture();
        }
    }

    void end()
    {
        if (!ctx) {
            return;
        }
        ctx->make_current();
        ImGui_ImplSDLRenderer2_Shutdown();
        ImGui_ImplSDL2_Shutdown();
        ctx.reset();
    }
};

ImTextureID logo_texture(void *user, const uint32_t *argb, int width, int height)
{
    SDL_Texture *tex = SDL_CreateTexture(static_cast<SDL_Renderer *>(user), SDL_PIXELFORMAT_ARGB8888,
                                         SDL_TEXTUREACCESS_STATIC, width, height);
    if (!tex) {
        return 0;
    }
    SDL_SetTextureBlendMode(tex, SDL_BLENDMODE_BLEND);
    SDL_SetTextureScaleMode(tex, SDL_ScaleModeLinear);
    SDL_UpdateTexture(tex, nullptr, argb, width * 4);
    return (ImTextureID)(intptr_t)tex;
}

void logo_release(void *, ImTextureID texture)
{
    SDL_DestroyTexture((SDL_Texture *)(intptr_t)texture);
}

